export const THEME_IDS = Object.keys(THEMES);
export const DEFAULT_THEME_ID = 'swiateczny';

export const DEFAULT_SETTINGS = {
  theme: DEFAULT_THEME_ID,
  showCountdown: true,
  countdownDate: '',
  countdownLabel: '',
};

export const getTheme = (id) => THEMES[id] || THEMES[DEFAULT_THEME_ID];

// Efektywne ustawienia odliczania: wartosci z panelu nadpisuja domyslne wartosci motywu.
export const getCountdown = (settings) => {
  const preset = getTheme(settings.theme);
  const date = settings.countdownDate || preset.countdownDate;
  if (settings.showCountdown === false || !date) return null;
  return { date: new Date(date), label: settings.countdownLabel || preset.countdownLabel };
};

